export const COMMON_FOODS = RAW.map(([name, serving, kcal, ...keys]) => ({ name, serving, kcal, keys }))

/** 말한 음식 이름 → 가장 잘 맞는 표준 음식 (긴 키워드 우선, "밥"이 "비빔밥"을 가로채지 않게) */
export function matchCommon(query) {
  const q = query.replace(/\s/g, '')
  let best = null
  for (const f of COMMON_FOODS) {
    for (const k of f.keys) {
      const hit = q === k || (k.length >= 2 && q.includes(k)) || (q.length >= 2 && k.includes(q))
      if (hit && (!best || k.length > best.len)) best = { food: f, len: k.length }
    }
  }
  // 한 글자 키워드("밥", "떡", "빵")는 정확히 일치할 때만
  if (!best) {
    const exact = COMMON_FOODS.find((f) => f.keys.includes(q))
    if (exact) return exact
  }
  return best?.food ?? null
}
